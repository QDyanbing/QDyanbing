import { readFile, writeFile } from 'node:fs/promises';

// Keep the original local badges as sources; embed them so GitHub loads one
// self-contained image whose two rows scale together instead of wrapping.
const rows = [
  ['typescript', 'react', 'ant-design', 'vue', 'javascript', 'html5', 'css'],
  ['nodejs', 'vite', 'vitest', 'playwright', 'eslint', 'pnpm', 'github-actions'],
];
const gap = 4;
const rowHeight = 26;
let width = 0;
const content = [];

for (const [rowIndex, row] of rows.entries()) {
  let x = 0;
  for (const name of row) {
    const source = (await readFile(new URL(`../assets/badges/${name}.svg`, import.meta.url), 'utf8')).trim();
    const badgeWidth = Number(source.match(/^<svg\b[^>]*\bwidth="(\d+)"/)?.[1]);
    if (!badgeWidth) throw new Error(`Missing width in ${name}.svg`);
    content.push(`  ${source.replace('<svg ', `<svg x="${x}" y="${rowIndex * rowHeight}" `)}`);
    x += badgeWidth + gap;
  }
  width = Math.max(width, x - gap);
}

const height = rowHeight * (rows.length - 1) + 20;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title">
  <title id="title">技能：语言与框架、构建与测试</title>
  <!-- Generated by node scripts/build-skill-badges.mjs from assets/badges/. -->
${content.join('\n')}
</svg>
`;
await writeFile(new URL('../assets/skill-badges.svg', import.meta.url), svg);
console.log(`Built skill-badges.svg: ${width} × ${height}, two rows of seven badges.`);
